-- 5. 자기 검증 — 틀리면 마이그레이션을 중단시킨다
-- ────────────────────────────────────────────────
-- DB 에 접속하지 않고 작성한 파일이라, 사람이 손으로 검산한 값을 코드로도 확인한다.
-- 하나라도 어긋나면 exception 이 나고 트랜잭션이 통째로 롤백되므로 절반만 반영될 일이 없다.

do $$
declare
  n_items      int;
  n_payments   int;
  sum_estimate bigint;
  sum_contract bigint;
  sum_paid     bigint;
  n_orphan     int;
  n_giftfund   int;
begin
  select count(*), coalesce(sum(estimate), 0), coalesce(sum(contracted), 0)
    into n_items, sum_estimate, sum_contract
    from public.budget_items;

  select count(*), coalesce(sum(amount), 0)
    into n_payments, sum_paid
    from public.payments;

  select count(*) into n_orphan
    from public.payments where budget_item_id is null;

  select count(*) into n_giftfund
    from public.budget_items where funding = '축의금';

  if n_items <> 35 then
    raise exception '예산 항목 수가 35건이 아니다: %', n_items;
  end if;
  if sum_estimate <> 24455000 then
    raise exception '예산 합계가 24,455,000 이 아니다: %', sum_estimate;
  end if;
  if sum_contract <> 23985000 then
    raise exception '계약금액 합계가 23,985,000 이 아니다: %', sum_contract;
  end if;
  if n_payments <> 7 then
    raise exception '결제 건수가 7건이 아니다: %', n_payments;
  end if;
  if sum_paid <> 1650000 then
    raise exception '결제 합계가 1,650,000 이 아니다: %', sum_paid;
  end if;
  if n_orphan <> 0 then
    raise exception '예산 항목에 연결되지 않은 결제가 있다(라벨/대분류 오타 의심): %건', n_orphan;
  end if;
  if n_giftfund <> 4 then
    raise exception '축의금 정산 항목이 4건이 아니다: %', n_giftfund;
  end if;

  raise notice '엑셀 예산 반영 완료 — 항목 %건 / 예산 % / 계약 % / 결제 %건 %',
    n_items, sum_estimate, sum_contract, n_payments, sum_paid;
end
$$;

