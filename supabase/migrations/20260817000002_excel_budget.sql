-- 그 뒤 사용자가 실제 계약을 진행하며 엑셀을 직접 채웠고, 두 숫자가 어긋난다.
--   · 대관료   추정 4,700,000 → 실제 3,900,000
--   · 컨시어지 추정   350,000 → 실제   300,000 (룰렛 이벤트 5만 할인)
--   · 식대 단가 추정 61,000/60,000 → 실제 58,000 (200명 × 58,000 = 11,600,000)
-- 부분 수정으로는 행 구조 자체가 달라(홀 대금을 계약금/잔금 두 행으로 쪼갠 방식 등)
-- 맞출 수 없어 전량 삭제 후 엑셀 35건을 그대로 다시 넣는다.
--
-- 검증된 합계 — 예산 24,455,000 · 계약 23,985,000 · 결제 1,650,000
-- (파일 맨 끝 DO 블록이 이 세 값을 실제로 검사하고, 틀리면 마이그레이션을 중단시킨다)
--
-- ────────────────────────────────────────────────
-- 원칙
-- ────────────────────────────────────────────────
--  1. 엑셀에 없는 금액은 만들지 않는다. 빈 칸은 NULL 이다.
--     예: 「피부 관리」는 예산 90,000원만 있고 계약금액 칸이 비어 있어 contracted = NULL 이다.
--         「본식 영상」은 예산 칸이 비어 있고 계약금액만 0원이다.
--  2. estimate(예산) · contracted(계약금액) · payments(실지출) 셋을 섞지 않는다.
--     budget_items.actual 과 paid_at 은 채우지 않는다 — 실지출은 payments 원장이 유일한
--     출처이고, budget_rollup.paid_sum 이 그 합계다. 두 곳에 같은 숫자를 적으면
--     앱에서 결제를 추가하는 순간 어긋난다.
--     ※ 통합 담당 주의 — 현재 app/src/budget 은 budget_items.actual 을 읽는다.
--       그대로 두면 실지출이 전부 0으로 보인다. budget_rollup 뷰로 갈아타야 한다.
--  3. 엑셀 memo 는 버리지 않는다. 연락처·주소·계좌는 vendor_contact 로 분리해
--     화면에서 바로 전화를 걸 수 있게 하고, 원문은 memo 끝에 「엑셀 원문:」 으로 남긴다.
--     사람이 급하게 적은 메모라 나중에 해석이 갈릴 수 있어 원문 보존이 가장 안전하다.
--
-- ────────────────────────────────────────────────
-- vendors 처리 방침
-- ────────────────────────────────────────────────
-- 규칙 — budget_items.vendor_name 은 업체를 아는 항목이면 항상 채운다.
--        그 이름이 vendors 에 등록돼 있으면 vendor_id 가 자동으로 붙는다(이름으로 조회).
--        vendors 에 등록하는 기준은 「다시 연락할 정보(전화·주소·계좌)가 있고,
--        앞으로 돈이 더 오갈 상대」다.
--   등록  — CA웨딩컨벤션(기존) · 더퀸한복 · REGALO (리갈로) · 이브닝글로우
--   미등록 — 스토리에스테틱: 연락처가 없고 이미 전액 결제가 끝나 더 오갈 돈이 없다.
--            백작 · PELLO: 예물 업체가 아직 둘 중 미정이라 지금 등록하면 잘못된 확정이 된다.
--            스드메 업체: 엑셀에 업체명 자체가 없다(담당 「조근경 이사」 연락처만 있음).
-- 이 규칙 덕에 vendor_id 가 비어 있어도 vendor_name/vendor_contact 로 화면이 온전하고,
-- 나중에 업체가 확정되면 vendors 에 한 줄 넣는 것만으로 연결이 살아난다.
--
-- ────────────────────────────────────────────────
-- owner 매핑
-- ────────────────────────────────────────────────
--   신랑 → 주호 · 신부 → 지영 · 공동 → 같이 · 빈 칸 → NULL
--   신랑측 → 주호 · 신부측 → 지영
--     ('측' 은 그 집안이 부담한다는 뜻이라 돈 자체는 우리 지출이 아니지만, 창구가 되어
--      챙겨야 할 사람은 그쪽 당사자다. assignee enum 에 '양가' 가 없으므로 담당자로 본다.
--      다만 이번 엑셀 예산 시트에는 신랑측/신부측이 한 건도 없어 실제로 쓰이지 않았다.)
--   payments.payer 도 같은 어휘(주호/지영/같이)로 맞췄다. 엑셀의 결제자 칸은
--   「실제 송금한 사람」이 아니라 「누가 부담하는가」를 뜻해서, 실제 입금자(송지영·이주호)는
--   description 과 memo 에 남겼다.
--
-- ────────────────────────────────────────────────
-- funding 분류
-- ────────────────────────────────────────────────
--   축의금 — 웨딩홀(CA웨딩컨벤션)이 예식 당일 청구하는 돈: 대관료 · 식대 · 컨시어지비용 · 원판사진
--            합계 15,965,000원. 예식 당일 축의금으로 정산한다.
--   선지출 — 나머지 전부. 외부 업체라 예식 전에 우리 현금이 먼저 나간다.
--   ※ 「신부대기실 꽃장식」도 CA 제공이지만 금액이 0원이라 집계에 영향이 없어 기본값을 뒀다.
--   ※ 「종이 청첩장」100,000원은 memo 가 「CA옵션예정」이다. 홀 옵션으로 확정되면
--      웨딩홀 청구분이 되므로 그때 축의금으로 옮길지 재검토할 것. 지금은 선지출이다.
--
--   ★ 이미 나간 돈이 뭉개지지 않게 — 대관료는 funding 이 축의금이지만 계약금 1,000,000원은
--     2026-08-09 에 이미 우리 돈으로 나갔다. 따라서 아래 집계는 반드시 잔액 기준으로 해야 한다.
--       축의금으로 낼 잔액 = sum(unpaid) where funding = '축의금'   → 14,965,000
--       예식 전 나갈 잔액   = sum(unpaid) where funding = '선지출'   →  7,370,000
--       이미 나간 우리 돈   = sum(payments.amount)                    →  1,650,000  (funding 무관)
--     sum(contracted) 를 그대로 쓰면 이미 낸 100만원을 또 내야 할 돈으로 세게 된다.
--     unpaid 는 budget_rollup 뷰에 이미 있다(contracted − paid_sum).
--
-- ────────────────────────────────────────────────
-- 재실행 안전성
-- ────────────────────────────────────────────────
-- payments → budget_items 순으로 전량 삭제하고 다시 넣으므로 몇 번을 돌려도 35건 + 7건이다.
-- (budget_items 를 먼저 지우면 FK 가 on delete set null 이라 payments 의 연결만 끊긴 채
--  행이 남아 결제가 두 배가 된다. 그래서 payments 를 먼저 지운다.)
-- vendors 는 이름으로 존재 확인 후 넣어 중복되지 않는다.

