-- 홀 계약금 실지출 반영
--
-- 20260809000006 시드는 actual/paid_at 을 전부 null 로 두었으나, 홀 계약금은 사실과 다르다.
-- wedding.html 일정표에 "2026-08-09 · D-391 · 계약 체결 · 계약금 100만원 납부 [완료]" 로
-- 명시되어 있다. null 로 두면 가계부 총 지출이 0원으로 보여, 이미 나간 100만원이
-- 집계에서 통째로 빠진다.
--
-- 시드 파일을 고치지 않고 별도 마이그레이션으로 처리하는 이유:
-- 이미 적용된 마이그레이션은 다시 실행되지 않으므로 006 을 수정해도 반영되지 않는다.
--
-- 재실행 안전: 이미 값이 들어 있으면 건드리지 않는다(사용자가 나중에 고친 값을 덮어쓰지 않도록).

update public.budget_items
   set actual  = 1000000,
       paid_at = date '2026-08-09'
 where label   = '홀 계약금 (선납)'
   and actual is null
   and paid_at is null;
