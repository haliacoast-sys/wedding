-- 계약 후기 이벤트 할인 반영 (2026-08-09, 확정)
--
-- 식대를 1인당 1,000원 할인받기로 확정됐다.
--
--   식대   200명 × 61,000 = 12,200,000   →   200명 × 60,000 = 12,000,000   (−200,000)
--   총액   4,700,000(대관) + 350,000(컨시어지) + 12,200,000 = 17,250,000
--          →                                    12,000,000 = 17,050,000
--   잔금   17,250,000 − 1,000,000(계약금 납부분) = 16,250,000
--          → 17,050,000 − 1,000,000              = 16,050,000
--
-- 계약금은 이미 납부했으므로 할인은 전액 잔금에서 빠진다.

update public.budget_items
   set estimate = 16050000,
       memo = '요약 탭 금액 구조 표 기준. 총액 17,050,000원에서 계약금 1,000,000원을 뺀 금액. '
              || '내역: 대관 4,700,000 + 컨시어지 350,000 + 식대 200명×60,000 = 12,000,000. '
              || '식대 단가는 계약 후기 이벤트로 1인당 1,000원 할인받아 61,000 → 60,000원이다(2026-08-09 확정). '
              || '내역을 별도 행으로 쪼개지 않는 이유는 계약금·잔금과 이중 계상되기 때문이다. '
              || '납부 시점 미확정 — 통상 예식 1개월 전 또는 당일이며 분납 여부를 확인할 것. '
              || '예금주가 에이엠푸드네트웍스로 업체명과 다르다.'
 where label = '홀 잔금';

-- 초과분 단가에도 할인이 적용되는지는 확인이 필요하다.
-- "계약 후기 이벤트"가 보증인원분에만 걸리는 조건일 수 있고, 200명을 넘기면
-- 1인당 1,000원 차이가 그대로 추가 비용이 된다.
update public.budget_items
   set memo = memo || ' ★ 2026-08-09 후기 이벤트로 보증인원 식대는 60,000원으로 확정. '
              || '다만 200명 초과분에도 이 할인가가 적용되는지는 확인되지 않았다. '
              || '초과분에 61,000원을 적용하면 인원이 늘수록 차액이 커지므로 서면으로 확인할 것.'
 where label = '하객 200명 초과분 식대 (당일 정산)';

-- 확인해야 할 일을 체크리스트에도 남긴다.
insert into public.tasks (title, note, category, due_date, assignee, status, sort_order)
select '후기 이벤트 할인 계약서 반영 확인',
       '식대 1인당 1,000원 할인(61,000 → 60,000)을 구두로 확정받았다. 수정 계약서나 견적서에 '
       || '반영된 문서를 반드시 받아둘 것. 구두 합의만으로는 잔금 정산 때 근거가 없다. '
       || '함께 확인할 것 — 200명 초과분 식대에도 같은 할인가가 적용되는지.',
       '예식장(CA웨딩컨벤션)',
       date '2026-08-23',
       '주호'::public.assignee,
       'todo'::public.task_status,
       250.0
where not exists (
  select 1 from public.tasks where title = '후기 이벤트 할인 계약서 반영 확인'
);
