-- 3. 라벨 오타 검증
-- ────────────────────────────────────────────────
-- 위 update 는 label 문자열이 한 글자라도 다르면 조용히 0행이 된다.
-- 30건 전부에 market_note 를 채웠으므로, 남아 있는 NULL 은 매칭 실패를 뜻한다.

do $$
declare
  n_missing int;
  missing_labels text;
begin
  select count(*), string_agg(label, ' / ')
    into n_missing, missing_labels
    from public.budget_items
   where market_note is null;

  if n_missing > 0 then
    raise warning '시세 메모가 비어 있는 예산 항목 %건 — 라벨 불일치로 update 가 빗나갔을 수 있다: %',
      n_missing, missing_labels;
  end if;
end $$;
