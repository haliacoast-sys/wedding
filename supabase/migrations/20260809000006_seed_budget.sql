--   상견례 · 예식장(CA웨딩컨벤션) · 예산·자금 · 스드메 · 본식업체 · 예단·예물·한복 ·
--   신혼집 · 혼수 · 신혼여행 · 청첩장·하객 · 본식준비
-- (tasks 의 「혼인신고·행정」 은 지출 항목이 없어 쓰지 않았다.)
--
-- ────────────────────────────────────────────────
-- 재실행 안전성
-- ────────────────────────────────────────────────
-- budget_items.id 가 gen_random_uuid() 기본값이라 그냥 insert 하면 두 번 적용 시 전부 중복된다.
-- 아래 insert 는 where not exists (select 1 from public.budget_items) 가드로 테이블이 비어
-- 있을 때만 삽입한다. INSERT ... SELECT 의 서브쿼리는 문 시작 시점 스냅샷을 보므로 같은 문에서
-- 삽입 중인 행이 보이지 않는다 — 첫 실행은 전량 삽입되고 두 번째부터는 0행이다.
-- vendors 는 별도 가드다. 다른 업체가 이미 들어와 있어도 CA웨딩컨벤션만 정확히 한 번 들어가도록
-- 테이블이 비었는지가 아니라 이름으로 확인한다.
-- vendor_id 는 UUID 를 박아 넣지 않고 이름으로 조회한다. gen_random_uuid() 가 만드는 값은
-- 실행할 때마다 달라져 하드코딩이 불가능하다.

