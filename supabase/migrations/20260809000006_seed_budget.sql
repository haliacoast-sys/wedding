--
-- ────────────────────────────────────────────────
-- 금액 출처 — 저장소 루트 wedding.html 한 곳뿐이다
-- ────────────────────────────────────────────────
-- 시세나 평균값 같은 외부 추정치는 한 건도 쓰지 않았다. 아래 다섯 곳에서만 읽었다.
--
--   (1) 「요약」 탭 > 금액 구조 표
--         홀 대관 4,700,000 · 컨시어지(필수) 350,000 · 식대 200명 × 61,000 = 12,200,000
--         주류·음료 서비스(0원) · 총액 17,250,000 · 계약금 1,000,000 · 잔금 16,250,000
--   (2) 「계약 내용」 탭 > 선택 사항 표
--         전문 사회자 정가 350,000 · 본식 영상 정가 440,000 (둘 중 1종만 서비스)
--   (3) 「계약 내용」 탭 > 이 홀에서 하지 않기로 한 것
--         웨딩 패키지 제안가 1,400,000 · 부속 헬퍼비 180,000
--         (둘 다 외부 진행으로 총액 17,250,000 에서 빠진 금액이다)
--   (4) 「계약 내용」 탭 > 홀 계약에 없는 별도 비용 표
--         본식 스냅 700,000 · 부케 200,000 · 축가/주례 각 300,000 · 현악 4중주 600,000
--         청첩장 100,000 · 모바일 청첩장 50,000 · 혼주 미용 女 180,000 / 男 55,000
--         스드메 일체와 턱시도 구두는 금액 없이 「외부」·「별도」 로만 적혀 있다
--   (5) 「비용」 탭 > 앞으로 늘어날 수 있는 비용
--         보증인원 초과 시 1인 61,000원 당일 추가 지불 (20명 초과면 1,220,000)
--
-- ────────────────────────────────────────────────
-- 원칙 — 미정 항목은 estimate 를 NULL 로 뒀다
-- ────────────────────────────────────────────────
-- wedding.html 에 금액이 적혀 있지 않은 항목(스드메·신혼여행·혼수·예단예물·신혼집 등)은
-- 예산 틀로서 행만 만들어 두고 estimate 를 NULL 로 뒀다. memo 첫머리에 「미정 — 견적 필요」 라고
-- 적어 두었으니 앱에서도 바로 구분된다. 조건부 금액(하객 초과분, 계약 변경 추가비, 사회자와
-- 본식 영상 중 서비스로 못 받는 쪽)도 같은 이유로 NULL 이다.
-- 그럴듯한 숫자를 채워 넣으면 나중에 그것을 실제 견적으로 착각하게 되므로 일부러 비워 뒀다.
-- 다만 헬퍼비는 wedding.html 에 180,000원이라는 값이 명시돼 있어 그 값을 썼고, 외부 업체
-- 실제 금액은 15~25만원 범위라는 점을 memo 에 적었다.
--
-- ────────────────────────────────────────────────
-- 분할 지급 — 홀 대금은 두 행으로 나눴다
-- ────────────────────────────────────────────────
-- 계약금 1,000,000(2026-08-09 납부) + 잔금 16,250,000 = 17,250,000 으로 총액과 정확히 맞는다.
-- 한 행으로 합치면 언제 얼마가 나가는지 알 수 없어 나눴다.
-- 대관·컨시어지·식대 내역은 따로 행으로 만들지 않고 잔금 행 memo 에 적었다. 내역을 행으로
-- 나누면 계약금·잔금과 이중 계상되어 합계가 34,500,000 이 되기 때문이다.
--
-- ────────────────────────────────────────────────
-- actual / paid_at
-- ────────────────────────────────────────────────
-- 아직 앱에서 지출을 기록하기 전이므로 전부 NULL 이다. insert 컬럼 목록에서 아예 빼서
-- 기본값 NULL 이 들어간다.
-- 주의 — 계약금 1,000,000원은 wedding.html 기준 2026-08-09 에 이미 납부 완료다.
-- 시드에서는 비워 뒀으니 앱에서 actual = 1000000, paid_at = 2026-08-09 으로 채워 넣어야
-- 실제 지출 현황과 맞는다.
--
-- ────────────────────────────────────────────────
-- category — 20260809000004_seed_tasks.sql 와 같은 체계를 쓴다
-- ────────────────────────────────────────────────
-- 나중에 체크리스트와 예산을 카테고리로 조인할 수 있어야 하므로 문자열을 그대로 맞췄다.
