-- 외부 스드메 검토용 행은 홀 진행으로 확정되어 의미가 없어졌다.
-- 남겨 두면 같은 비용이 두 줄로 보여 예산을 이중으로 읽게 된다.
delete from public.budget_items
 where label = '외부 스드메 일체 (드레스 · 턱시도 · 헤어메이크업 · 스튜디오)';

-- 12:30 변경과 패키지 제외를 전제로 만든 조건부 비용 행도 근거가 사라졌다.
delete from public.budget_items
 where label = '계약 변경(예식 12:30 · 웨딩 패키지 제외)에 따른 추가 비용';

-- 홀 잔금 행이 패키지를 포함하지 않는다는 점을 분명히 해 둔다.
update public.budget_items
   set memo = memo || E'\n\n' ||
              '※ 2026-08-09 웨딩 패키지(1,400,000원)를 홀 진행으로 확정하면서 별도 행으로 추가했다. '
              || '이 행에는 패키지가 포함돼 있지 않다. CA 에 앞으로 낼 돈은 이 행과 패키지 행의 합인 '
              || '17,450,000원이다.'
 where label = '홀 잔금'
   and memo not like '%웨딩 패키지(1,400,000원)를 홀 진행으로 확정%';

update public.budget_items
   set memo = memo || ' ★ 2026-08-09 웨딩 패키지를 홀 진행으로 확정했으므로, 이 헬퍼비가 패키지에 '
              || '포함되는지 별도 청구인지 반드시 확인할 것. 포함이면 이 행은 지워야 한다.'
 where label = '본식 당일 헬퍼비'
   and memo not like '%웨딩 패키지를 홀 진행으로 확정%';

