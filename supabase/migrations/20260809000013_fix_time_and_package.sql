-- 확정 사항 반영 (2026-08-09)
--   ① 예식 시간을 2027-09-04(토) 11:00 으로 확정. 12:30 변경 검토는 종료.
--   ② 웨딩 패키지(1,400,000원)를 홀에서 진행하는 것으로 확정. 외부 진행 검토는 종료.
--
-- ── ① 시간 ──────────────────────────────────────────────
-- 11:00 은 계약서 원본 시간이다. 즉 변경 신청도, 홀의 서면 동의도 필요 없어졌다.
-- 그동안 "12:30 변경 예정 · 홀 동의 대기"로 남아 있던 불확실성이 통째로 사라진다.
-- 70분 슬롯에 12:30 이 실제로 존재하는지 확인해야 했던 문제도 함께 없어진다.
--
-- day_of_events 는 예식 기준 상대 분(offset_min)으로만 저장돼 있으므로
-- 아래 ceremony_at 한 줄을 고치면 진행표 26개 항목의 시각이 전부 따라 움직인다.
-- 검산 — 계약 조건과 그대로 맞아떨어진다:
--   offset −30 → 10:30  연회 이용 시작 (계약: 예식 30분 전)
--   offset +70 → 12:10  식사 시작      (wedding.html 의 11:00 기준 "약 12:10"과 일치)
--   offset +120 → 13:00 연회 종료      (계약: 총 2시간 30분, 10:30~13:00)
--
-- ── ② 웨딩 패키지 ───────────────────────────────────────
-- 홀 청구액이 늘어난다.
--   기존 총액  4,700,000(대관) + 350,000(컨시어지) + 12,000,000(식대) = 17,050,000
--   패키지 추가                                        + 1,400,000 = 18,450,000
--   잔금       18,450,000 − 1,000,000(기납부 계약금)              = 17,450,000
-- 홀 잔금 행을 키우지 않고 별도 행으로 둔다. 그래야 패키지 금액이 시세(스드메 중간가)와
-- 나란히 비교되고, 나중에 빼거나 조정할 때 한 행만 건드리면 된다.

-- ── 시간 확정 ──
update public.day_of_config
   set ceremony_at = '2027-09-04 11:00+09'::timestamptz,
       note = '2026-08-09 확정 — 2027년 9월 4일(토) 11:00. 계약서 원본 시간이므로 변경 신청이나 '
              || '홀 서면 동의가 필요 없다. 연회 이용 가능 시간은 10:30~13:00(예식 30분 전부터 2시간 30분), '
              || '홀 사용 70분, 식사 시작 약 12:10. '
              || '진행표 각 항목은 예식 기준 상대 분으로만 저장되므로, 시간이 다시 바뀌면 이 행만 고치면 된다.'
 where id = 1;

-- 신부 준비가 11:00 예식에서는 빠듯해진다. 12:30 안이 가졌던 유일한 장점이 이것이었다.
update public.day_of_events
   set note = coalesce(note || ' ', '')
              || '★ 11:00 예식이라 시작이 이르다(예식 4시간 전 = 07:00). 샵 예약 시 이 시간에 '
              || '문을 여는지 먼저 확인할 것. 새벽 예약이 안 되면 앞의 준비 항목 전체를 다시 짜야 한다.'
 where title = '신부 헤어·메이크업'
   and note not like '%11:00 예식이라%';

-- ── 웨딩 패키지 ──
