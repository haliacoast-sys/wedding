-- 스드메 체크리스트를 홀 패키지 기준으로 정리 (2026-08-09)
--
-- 웨딩 패키지 140만원의 구성은 wedding.html 기준 이렇다:
--   본식     — 드레스 · 턱시도, 본식 헤어·메이크업   (정가 2,000,000)
--   스튜디오 — 헤어·메이크업, 리허설 촬영            (정가 1,200,000)
-- 즉 스(스튜디오 촬영)·드(드레스)·메(헤어메이크업)가 모두 포함이고 턱시도까지 들어간다.
--
-- 시드는 외부 스드메를 직접 알아보는 흐름을 전제로 짜여 있었다.
-- 홀 진행으로 확정됐으므로 업체 탐색·계약 관련 항목은 할 일이 아니게 됐다.
-- 반면 "무엇이 포함인지 확인"과 "포함 안 된 것에 얼마를 더 쓸지"는 새로 생긴 할 일이다.

-- ── 근거가 사라진 항목 ──
delete from public.tasks
 where category = '스드메'
   and title in ('스드메 업체 3곳 이상 상담 예약', '스드메 계약 체결');

-- ── 예산 항목은 성격이 바뀌었다 ──
-- 스드메 총예산은 140만원으로 이미 정해졌다. 이제 정할 것은 패키지에 포함되지 않는
-- 추가 지출(원본 구매, 구두, 드레스 업그레이드 등)을 어디까지 허용할지다.
update public.tasks
   set title = '패키지 외 추가 지출 상한 정하기',
       note  = '스드메 본체는 홀 패키지 140만원으로 확정됐다. 남은 것은 패키지에 포함되지 않는 '
               || '지출을 어디까지 할지다 — 스튜디오 원본 구매(통상 30~50만원), 신랑 구두, '
               || '드레스 업그레이드 비용, 헬퍼비(포함 여부 확인 필요). '
               || '이런 항목은 현장에서 하나씩 권유받게 되므로 상한을 미리 정해두지 않으면 계속 늘어난다.'
 where category = '스드메'
   and title    = '스드메 예산 상한과 우선순위 정하기';

update public.tasks
   set title = '웨딩플래너 이용 여부 결정',
       note  = '홀 패키지로 스드메가 묶여 있어 플래너의 역할이 줄어든다. '
               || '스드메 업체 섭외가 플래너의 주된 값어치인데 그 부분이 이미 해결된 상태다. '
               || '그래도 쓸지, 쓴다면 어느 범위까지 맡길지 판단할 것.'
 where category = '스드메'
   and title    = '웨딩플래너 이용 여부 결정';

-- ── 남은 실무 항목은 상대가 홀 협력업체로 바뀐다 ──
update public.tasks
   set note = coalesce(note || ' ', '')
              || '★ 홀 웨딩 패키지에 포함된 항목이다. 외부 업체가 아니라 홀 협력업체와 진행하게 되므로, '
              || '일정과 연락 창구를 홀 담당자(이도경)에게 먼저 확인할 것.'
 where category = '스드메'
   and title in ('리허설 촬영일 확정', '드레스 투어 (3벌 이상 피팅)', '리허설 촬영 진행',
                 '본식 헤어·메이크업 팀 확정 및 리허설', '스튜디오 원본·앨범 셀렉 마감')
   and note not like '%홀 웨딩 패키지에 포함된 항목이다%';

-- ── 새로 생긴 할 일 ──
-- 구성 확인이 가장 급하다. 무엇이 포함인지 모르면 추가 비용을 예측할 수 없고,
-- 시세(충청 스드메 중간가 270만원) 대비 유불리도 판단할 수 없다.
insert into public.tasks (title, note, category, due_date, assignee, status, sort_order)
select '웨딩 패키지 140만원 구성 내역 받기',
       '홀 담당자에게 문서로 요청할 것. 확인할 항목 — '
       || '① 드레스 벌수(본식 몇 벌, 리허설 몇 벌) '
       || '② 스튜디오 원본 제공 여부(따로 사면 통상 30~50만원 추가) '
       || '③ 앨범·액자 포함 여부와 수량 '
       || '④ 헬퍼비 180,000원이 포함인지 별도 청구인지 '
       || '⑤ 드레스 업그레이드 비용 발생 조건. '
       || '충청 스드메 패키지 중간가가 270만원이라 140만원은 절반 수준이지만, '
       || '구성이 빈약하면 추가 비용으로 결국 시세에 수렴한다. 구성을 봐야 판단이 선다.',
       '스드메',
       date '2026-08-23',
       '지영'::public.assignee,
       'todo'::public.task_status,
       260.0
where not exists (
  select 1 from public.tasks where title = '웨딩 패키지 140만원 구성 내역 받기'
);
