-- ── 외부업체 사전 승인 항목의 대상을 정확히 한다 ──
-- 약관 제6조는 외부 업체 사용 시 사전 승인을 요구한다. 다만 실질적으로 문제가 되는 것은
-- 예식 당일 홀에 들어오는 업체(본식 스냅·영상)다. 스튜디오 촬영은 홀 밖에서 이뤄지므로
-- 대상이 아닐 가능성이 크지만, 판단을 임의로 하지 말고 홀에 확인하게 한다.
--
-- 마감일도 당긴다. 기존 2027-04-10 은 본식 스냅 예약(2027-03-28)보다 뒤였다.
-- 승인이 거절되면 이미 계약한 업체를 못 쓰게 되므로 순서가 뒤집혀 있으면 안 된다.
update public.tasks
   set title    = '외부업체 사전 승인 요청 (제6조) — 예약 전에 먼저',
       due_date = date '2027-03-14',
       note     = '약관 제6조 — 주류·사진·영상·장식 등 외부 업체 사용 시 홀의 사전 승인이 필수이고, '
                  || '승인 없이 사용하면 사업자가 면책된다. '
                  || '★ 반드시 업체 계약 전에 승인을 받을 것. 계약 후에 거절당하면 위약금을 물고 다시 구해야 한다. '
                  || '대상 — 본식 스냅, 본식 영상처럼 예식 당일 홀에 들어오는 업체. '
                  || '스튜디오 웨딩 화보는 홀 밖에서 촬영하므로 대상이 아닐 가능성이 크지만, '
                  || '임의로 판단하지 말고 함께 물어볼 것.'
 where title = '외부 스드메·스냅 업체 사전 승인 요청';
