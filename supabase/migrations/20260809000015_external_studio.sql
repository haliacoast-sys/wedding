-- 스튜디오 웨딩 화보를 외부 업체와 계약 (2026-08-09 확인)
--
-- 홀 웨딩 패키지 140만원의 구성은 두 덩어리다.
--   본식     — 드레스 · 턱시도, 본식 헤어·메이크업   (정가 2,000,000)
--   스튜디오 — 헤어·메이크업, 리허설 촬영            (정가 1,200,000)
-- 이 중 스튜디오 촬영을 원하는 스타일의 외부 업체와 이미 계약했다.
-- 따라서 패키지의 스튜디오 몫은 쓰지 않게 된다.
--
-- ── 그래도 패키지를 유지하는 것이 유리한 이유 ──
-- 한국소비자원 참가격 충청 개별 중간가: 스튜디오 1,000,000 · 드레스 1,410,000 · 메이크업 760,000.
-- 드레스 하나만 해도 1,410,000원이라 패키지 140만원을 이미 넘는다.
-- 패키지는 드레스에 더해 턱시도와 본식 헤어·메이크업까지 포함하므로,
-- 스튜디오 몫을 전부 버려도 따로 계약하는 것보다 싸다.
--
-- 다만 드레스 벌수에 따라 판단이 달라진다. 1벌뿐이면 충청 중간가 1,410,000 이
-- 몇 벌 기준인지와 대조해야 한다. 구성 확인이 여전히 선결 조건이다.

-- ── 외부 스튜디오 계약을 예산에 반영 ──
-- 계약했는데 예산에 없으면 총 지출이 실제보다 적게 보인다.
insert into public.budget_items (label, category, estimate, memo, market_avg, market_note)
select '스튜디오 웨딩 화보 (외부 계약)',
       '스드메',
       null,
       '2026-08-09 확인 — 원하는 스타일의 외부 스튜디오와 이미 계약했다. 계약 금액을 확인해 채울 것. '
       || '홀 웨딩 패키지에도 스튜디오 촬영이 포함돼 있으나(정가 1,200,000) 이쪽을 쓰기로 했으므로 '
       || '패키지의 스튜디오 몫은 사용하지 않는다. '
       || '★ 확인할 것 — 이 계약에 촬영일 헤어·메이크업이 포함인지. 미포함이면 별도 비용이 발생한다. '
       || '패키지에 스튜디오 헤어·메이크업이 들어 있으므로, 그것만 촬영일에 쓸 수 있는지 홀에 문의할 것.',
       1000000,
       '한국소비자원 참가격 기준 충청 지역 스튜디오 중간가 1,000,000원. '
       || '개별 중간가는 스튜디오 1,000,000 · 드레스 1,410,000 · 메이크업 760,000원이며, '
       || '셋을 묶은 스드메 패키지 중간가는 2,700,000원이다(묶으면 약 470,000원 저렴). '
       || '출처: 한국소비자원 참가격 인용 기사(2025~2026).'
where not exists (
  select 1 from public.budget_items where label = '스튜디오 웨딩 화보 (외부 계약)'
);

-- ── 패키지 행에 스튜디오 미사용 사실을 남긴다 ──
update public.budget_items
   set memo = memo || E'\n\n'
              || '※ 2026-08-09 — 스튜디오 웨딩 화보는 외부 업체와 계약했으므로 패키지의 스튜디오 몫'
              || '(정가 1,200,000)은 사용하지 않는다. 그럼에도 패키지 유지가 유리하다 — '
              || '충청 드레스 중간가만 1,410,000원이라 드레스 하나로 이미 140만원을 넘고, '
              || '패키지에는 턱시도와 본식 헤어·메이크업까지 포함돼 있다. '
              || '★ 협상 여지 — 스튜디오를 쓰지 않으니 금액 조정이 가능한지, 또는 스튜디오 '
              || '헤어·메이크업만 외부 촬영일에 쓸 수 있는지 문의할 것.'
 where label = '웨딩 패키지 (홀 진행)'
   and memo not like '%스튜디오 웨딩 화보는 외부 업체와 계약%';

-- 원본 구매는 이제 외부 스튜디오와의 문제다.
update public.budget_items
   set memo = memo || ' ★ 2026-08-09 — 스튜디오를 외부 계약했으므로 원본 제공 조건도 '
              || '홀이 아니라 그 업체와의 계약서를 확인해야 한다.'
 where label = '스튜디오 원본 구매'
   and memo not like '%스튜디오를 외부 계약했으므로%';

-- ── 리허설 촬영 관련 항목의 상대가 홀이 아니라 외부 업체다 ──
-- 20260809000014 에서 "홀 협력업체와 진행"이라고 붙여 둔 메모가 이 항목들에는 틀렸다.
update public.tasks
   set note = replace(
                note,
                '★ 홀 웨딩 패키지에 포함된 항목이다. 외부 업체가 아니라 홀 협력업체와 진행하게 되므로, 일정과 연락 창구를 홀 담당자(이도경)에게 먼저 확인할 것.',
                '★ 스튜디오 촬영은 외부 업체와 계약했다. 홀 패키지가 아니라 그 업체와 직접 조율할 것.'
              )
 where category = '스드메'
   and title in ('리허설 촬영일 확정', '리허설 촬영 진행', '스튜디오 원본·앨범 셀렉 마감');

