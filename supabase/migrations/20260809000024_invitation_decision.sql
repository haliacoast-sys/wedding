       note  = '2026-08-23 하객 집계가 끝나면 필요 부수를 계산할 것 — 하객 수의 60% 선(부부·가족 단위로 '
               || '한 장씩 나감), 여유 포함 130~150부 예상. '
               || '★ 비교 기준 — CA 조건은 100,000원에 모바일 청첩장(50,000원 상당) 서비스 포함이다. '
               || '몇 부 기준인지와 초과분 단가를 확인해야 비교가 된다. '
               || '외부 시세는 200장 20~30만원(장당 1,000~1,500원)이 흔하고 소량일수록 장당 단가가 오른다. '
               || '★ 모바일을 직접 만들 수 있다는 것이 종이를 외부로 돌릴 이유는 아니다. 두 결정은 독립적이다. '
               || '홀 조건이 싸면 홀에서 하고 모바일은 덤으로 받으면 되고, 홀 모바일이 마음에 안 들면 '
               || '그때 직접 만들면 된다.',
       due_date = date '2026-09-13'
