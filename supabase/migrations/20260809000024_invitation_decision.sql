-- 청첩장 업체 선택 판단 기준 (2026-08-09)
--
-- "모바일은 직접 만들 수 있으니 종이도 외부로 돌릴까"라는 검토.
-- 두 결정은 사실 독립적이다. 모바일을 직접 만들 수 있다는 것은 홀 모바일이
-- 마음에 안 들 때 갈아탈 선택지가 있다는 뜻이지, 종이를 외부로 돌릴 이유는 아니다.
--
-- 종이 청첩장의 판단은 부수 하나로 갈린다.
--   시장 시세  200장 기준 20~30만원이 흔한 가격대 → 장당 1,000~1,500원
--   소량 인쇄  부수가 적을수록 장당 단가가 올라간다(인쇄 특성)
--   CA 조건    100,000원 — 부수 기준 미확인
--
-- 필요 부수 추정: 하객 200명 × 60% = 약 120부(부부·가족 단위로 한 장씩 나감), 여유 포함 130~150부.
--
-- 손익분기
--   CA 10만원이 100부 이상 기준이면 장당 1,000원 이하 → 시세 하단, 홀 쪽이 유리하다.
--   여기에 모바일 청첩장(5만원 상당)까지 서비스로 딸려오므로 격차가 더 벌어진다.
--   반대로 10만원이 50부 같은 소량 기준이면 외부 소량 인쇄가 쌀 수 있다.
--
-- 결론: 지금 결정할 일이 아니다. 발주는 2027-07-11 이고 부수는 하객 집계(2026-08-23) 후에 나온다.
-- 지금 할 것은 "10만원이 몇 부 기준인지" 확인해 두는 것뿐이다.

update public.budget_items
   set memo = '2026-08-09 — 별도 비용 표 기준 100,000원. 이 계약으로 모바일 청첩장이 서비스로 딸려온다. '
              || E'\n\n'
              || '[외부 업체와 비교하는 법] 판단은 부수 하나로 갈린다. '
              || '시장 시세는 200장 기준 20~30만원이 흔해 장당 1,000~1,500원 선이고, '
              || '부수가 적을수록 장당 단가가 올라간다. '
              || '필요 부수는 하객 200명 기준 약 120부(하객 수의 60% — 부부·가족 단위로 한 장씩 나감), '
              || '여유 포함 130~150부다. '
              || 'CA 100,000원이 100부 이상 기준이면 장당 1,000원 이하라 시세 하단이고, '
              || '모바일(50,000원 상당)까지 서비스로 붙어 홀 쪽이 확실히 유리하다. '
              || '반대로 50부 같은 소량 기준이라면 소량 특화 인쇄 업체가 쌀 수 있다. '
              || E'\n\n'
              || '★ 지금 결정할 일이 아니다. 인쇄 발주는 2027-07-11 이고 부수는 하객 집계(2026-08-23) 후에 나온다. '
              || '지금 할 것은 "100,000원이 몇 부 기준인지"와 "초과분 단가"를 확인해 두는 것뿐이다. '
              || '미리 계약하면 돈이 묶이고, 11개월 사이에 디자인 취향도 바뀐다.'
 where label = '종이 청첩장';

