-- 사용자 결정 반영 (2026-08-09)
--   · 신혼여행을 가지 않기로 함
--   · 예물을 하지 않기로 함
--
-- 시드(20260809000004, 20260809000006)에 이미 들어간 항목을 지운다.
-- 시드 파일 자체를 고치지 않는 이유: 이미 적용된 마이그레이션은 재실행되지 않으므로
-- 원본을 고쳐도 반영되지 않는다. 또 "처음부터 없었던 것"이 아니라 "넣었다가 뺀 결정"이라
-- 이력이 남는 편이 낫다. 되돌리려면 이 마이그레이션을 뒤집는 새 마이그레이션을 쓰면 된다.
--
-- 주의: '예단·예물·한복' 카테고리를 통째로 지우지 않는다. 예단과 한복은 유지한다.
--       사용자가 그만두기로 한 것은 예물뿐이다.

-- ── 신혼여행 (tasks 7건, budget 2건) ──
delete from public.tasks        where category = '신혼여행';
delete from public.budget_items where category = '신혼여행';

-- ── 예물 (tasks 2건, budget 1건) ──
delete from public.tasks
 where category = '예단·예물·한복'
   and title in ('예물 브랜드·예산 결정', '예물 구매 및 사이즈 조절·각인');

delete from public.budget_items
 where category = '예단·예물·한복'
   and label = '예물 (반지 등)';

-- 예단과 예물이 한 항목에 묶여 있던 건은 지우지 않고 예물만 떼어낸다.
update public.tasks
   set title = '예단 범위 양가 합의',
       note  = coalesce(note || ' ', '') || '(2026-08-09 예물은 하지 않기로 결정하여 예단만 남김)'
 where category = '예단·예물·한복'
   and title    = '예단·예물 범위 양가 합의';

-- ════════════════════════════════════════════════════════════
-- 계약서 제7조 표시 정정
--
-- wedding.html 은 제7조(계약해제 및 위약금 기준)에 손으로 그어진 표시를 "큰 X"로 읽고,
-- "이 조항은 적용하지 않는다는 뜻일 수도 있다"는 낙관적 해석을 함께 남겨 두었다.
-- 사용자 확인 결과 그 표시는 X 가 아니라 별표(★)이며, 담당자가 "중요한 조항"이라고
-- 짚어 준 것이었다.
--
-- 결론이 정반대로 바뀐다 — 제7조는 무효화된 것이 아니라 그대로 살아 있다.
-- 따라서 wedding.html 이 지적한 "위약금 기준이 공정위 소비자분쟁해결기준보다 불리하다"는
-- 문제가 실제로 적용된다. 문의할 일은 없어졌지만 위험은 남았으므로,
-- 항목을 지우지 않고 완료 처리한 뒤 남은 위험을 note 에 적는다.
-- ════════════════════════════════════════════════════════════

update public.tasks
   set status = 'done',
       title  = '제7조 별표 확인 완료 — 위약금 조항 유효',
       note   = '담당자가 별표(★)로 "중요"를 표시한 것이며 조항 무효 표시가 아니다. '
                || '따라서 제7조 위약금 기준이 그대로 적용된다. 이 기준은 공정거래위원회 '
                || '소비자분쟁해결기준(예식업)보다 불리하다 — 공정위 기준은 예식 90일 전까지 '
                || '위약금 없이 해제할 수 있으나, 계약서는 149일 전부터 10%를 물린다. '
                || '해제 가능성을 조금이라도 고려한다면 이 차이를 먼저 계산할 것.'
 where title like '%7조%';
