-- 확정 사항 반영 (2026-08-09)
--   ① 주례 없음 — 주례 없는 예식으로 진행
--   ② 접수(축의금·방명록)는 친척들이 맡음
--   ③ 헬퍼비는 패키지 포함이 아니라 전부 별도 청구
--
-- ── ① 주례를 빼면 예식 중간이 빈다 ──
-- 진행표 +17분에 '주례사 또는 양가 대표 인사' 10분이 잡혀 있다.
-- 주례를 없앤다고 이 10분을 그냥 삭제하면 예식이 앙상해진다.
-- 주례 없는 예식에서는 보통 이 자리를 두 사람의 편지 낭독이나 성혼 선언문 낭독,
-- 양가 아버지 인사말로 채운다. 그래서 삭제가 아니라 내용을 바꾼다.
--
-- ── ③ 헬퍼는 2회 발생할 수 있다 ──
-- 헬퍼비는 통상 1회당 200,000~300,000원이고 스튜디오 촬영일과 본식에 각 1회씩 든다.
-- 이 커플은 스튜디오를 외부 계약했으므로 촬영일 헬퍼가 그 계약에 포함인지 별도인지
-- 확인이 필요하다. 별도라면 본식 헬퍼와 합쳐 두 번 나간다.

-- ── ① 주례 제거 ──
delete from public.day_of_roles where role = '주례';
delete from public.budget_items where label = '주례';

