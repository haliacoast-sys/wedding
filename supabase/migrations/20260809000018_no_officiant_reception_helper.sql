   set title = '편지 낭독문 · 성혼 선언문 작성',
       note  = '2026-08-09 주례 없는 예식으로 확정했다. 주례사가 있던 자리(예식 시작 +17분, 10분)를 '
               || '두 사람의 편지 낭독이나 성혼 선언문으로 채운다. '
               || '★ 2주 전까지 써두고 소리 내어 읽어보며 분량을 맞출 것. 10분을 넘기면 하객이 지친다. '
               || '★ 완성되면 사회자에게 공유할 것 — 주례가 없으면 흐름을 이어줄 사람이 사회자뿐이다.',
       due_date = date '2027-08-21'
 where title = '주례 여부 결정';

-- ── ② 접수는 친척이 맡는다 ──
-- 사례비를 0 이 아니라 null 로 둔다. 친척에게는 현금 봉투 대신 식사 대접이나
-- 답례품으로 갈음하는 경우도 많아 관례가 갈린다. 임의로 0 을 박으면
-- 나중에 봉투를 준비해야 할 때 예산에서 누락된다.
update public.day_of_roles
   set fee  = null,
       note = '2026-08-09 친척들이 맡기로 확정. 이름과 연락처를 채울 것. '
              || '★ 사례비는 판단이 필요하다. 친구에게 부탁할 때는 5~10만원 봉투가 관례지만, '
              || '친척이면 식사 대접이나 답례품으로 갈음하는 경우도 많다. 양가 어른들과 상의해 정할 것. '
              || '봉투로 하기로 하면 이 fee 값을 채워 당일 준비물에 반영되게 할 것. '
              || '★ 돈을 직접 다루는 자리다. 축의금함 위치, 명단 기록 방식, 예식 중 보관 장소를 '
              || '전날까지 알려줄 것.'
 where role in ('접수 · 신랑측', '접수 · 신부측');

