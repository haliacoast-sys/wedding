               || '양가 아버지 인사말로 채운다. 그냥 비우면 예식 중간이 앙상해진다. '
               || '★ 낭독문은 2주 전까지 써두고 한 번 소리 내어 읽어볼 것. 분량이 길면 하객이 지친다. '
               || '★ 사회자에게 이 순서의 진행 방식을 미리 알려줄 것 — 주례가 없으면 흐름을 이어줄 사람이 '
               || '사회자뿐이다.'
