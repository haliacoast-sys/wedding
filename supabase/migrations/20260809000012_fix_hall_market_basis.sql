-- 홀 시세 비교 기준 통일
--
-- 20260809000011 은 '홀 잔금' 행에 충청 중간가 "총액" 15,500,000원을 넣었다.
-- market_note 의 서술은 정확하다 — CA 총액 17,050,000원이 충청 중간가보다
-- 약 1,550,000원(10%) 높다고 총액끼리 비교했다.
--
-- 그런데 이 행의 estimate 는 총액이 아니라 잔금 16,050,000원(= 총액 − 기납부 계약금)이다.
-- 화면이 두 값을 그대로 빼면 +550,000 이 나와, 실제 차이 1,550,000 원을 3분의 1로
-- 축소해 보여준다. 숫자만 보는 사람은 "시세보다 조금 비싼 정도"로 오해하게 된다.
--
-- 두 값의 기준을 잔금으로 맞춘다.
--   충청 중간가 총액 15,500,000 − 기납부 계약금 1,000,000 = 14,500,000
--   16,050,000 − 14,500,000 = 1,550,000  ← 총액끼리의 실제 차이와 일치
--
-- 새로운 시세를 지어내는 것이 아니라 같은 출처의 값을 같은 기준으로 옮긴 것이다.

update public.budget_items
   set market_avg = 14500000,
       market_note = '※ 이 행은 잔금이므로 시세도 잔금 기준으로 환산했다 — '
                     || '충청 중간가 총액 15,500,000원에서 기납부 계약금 1,000,000원을 뺀 값이다. '
                     || '총액끼리 비교하면 CA 17,050,000원 vs 충청 중간가 15,500,000원으로 '
                     || '차이는 1,550,000원(10%)이며, 이 행의 차액과 같다. '
                     || E'\n\n' || market_note
 where label = '홀 잔금'
   and market_avg = 15500000;
