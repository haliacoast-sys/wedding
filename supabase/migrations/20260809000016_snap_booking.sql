-- 본식 스냅 항목 보강 (2026-08-09)
--
-- ── 왜 당기는가 ──
-- 예식이 2027-09-04(토)이고 9월은 성수기다. 본식 스냅 작가는 주말에 일이 몰려
-- 인기 작가일수록 1년 전에도 마감된다. 기존 마감 2027-03-28(D-160)은
-- "5개월 전 예약 필요"라는 홀 안내에 맞춘 값이지만, 그건 최소 기준이지
-- 원하는 작가를 고를 수 있는 시점이 아니다. 알아보는 것과 계약하는 것을 나누고
-- 알아보기를 크게 당긴다.
--
-- ── 이 커플 특유의 함정 ──
-- 본식스냅 업체 상당수가 "스냅 + 원판" 합본 상품으로 판매한다.
-- 그런데 CA웨딩컨벤션은 원판 촬영이 대관료에 포함이고 외부 촬영이 금지돼 있다.
-- 합본을 계약하면 원판 값을 두 번 내고, 정작 그 작가는 원판을 찍지도 못한다.
-- 반드시 스냅 단독 상품으로 견적을 받아야 한다.

update public.tasks
   set title    = '본식 스냅 작가 알아보기 (스냅 단독 상품으로)',
       due_date = date '2026-11-14',
       note     = '★ 반드시 "스냅 단독" 상품으로 문의할 것. 업체 상당수가 스냅+원판 합본으로 파는데, '
                  || 'CA는 원판이 대관료에 포함이고 외부 촬영이 금지돼 있다. 합본을 계약하면 원판 값을 '
                  || '두 번 내면서 그 작가는 원판을 찍지도 못한다. "원판은 홀 제공이라 스냅만 필요하다"고 '
                  || '먼저 말하면 견적이 달라진다. '
                  || '가격대 — 신진 40~50만 / 실장급 60~100만 / 수석·대표급 130~250만. '
                  || 'CA 별도비용 표의 700,000원은 실장급 하단이고 충청 시세 조사값은 800,000원이다. '
                  || '★ 2027-09-04는 토요일이고 9월은 성수기다. 인기 작가는 1년 전에도 마감되므로 '
                  || '일찍 알아볼수록 선택지가 넓다.'
 where title = '본식 스냅 작가 비교·예약';

-- 알아보기와 계약을 분리한다. 계약은 외부업체 사전 승인(제6조) 이후여야 한다.
insert into public.tasks (title, note, category, due_date, assignee, status, sort_order)
select '본식 스냅 계약 체결',
       '★ 반드시 외부업체 사전 승인(약관 제6조)을 받은 뒤에 계약할 것. 승인 없이 사용하면 '
       || '사업자가 면책되고, 계약 후 거절당하면 예약금을 날린다. 본식스냅 예약금은 통상 환불 불가다. '
       || '계약 전 확인 목록 — '
       || '① 스냅 단독 상품인지(원판 중복 아닌지) '
       || '② 보정본 몇 컷인지(업체별로 60~70컷 선) '
       || '③ 원본 전체를 주는지, 전달 방식과 보관 기간 '
       || '④ 신부대기실·폐백 촬영이 기본 포함인지 추가금인지 '
       || '⑤ 작가가 바뀔 수 있는지(실장급 계약 후 다른 작가 배정되는 사례가 있다) '
       || '⑥ 예약금 환불 조건.',
       '본식업체',
       date '2027-03-20',
       '같이'::public.assignee,
       'todo'::public.task_status,
       3850.0
where not exists (
  select 1 from public.tasks where title = '본식 스냅 계약 체결'
);

-- 예산 메모에도 합본 함정을 남긴다. 견적을 볼 때 바로 보이는 자리다.
update public.budget_items
   set memo = coalesce(memo || ' ', '')
              || '★ 스냅 단독 상품으로 견적받을 것. 업체 상당수가 스냅+원판 합본으로 파는데 CA는 '
              || '원판이 대관료 포함이고 외부 촬영 금지라, 합본이면 원판 값을 두 번 내게 된다. '
              || '가격대는 신진 40~50만 / 실장급 60~100만 / 수석·대표급 130~250만이며 '
              || '이 행의 700,000원은 실장급 하단이다.'
 where label = '본식 스냅'
   and memo not like '%스냅 단독 상품으로 견적받을 것%';
