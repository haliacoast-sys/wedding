              || '승인 없이 사용하면 사업자가 면책된다. '
              || '★ 반드시 업체 계약 전에 승인을 받을 것. 계약 후 거절당하면 위약금을 물고 다시 구해야 한다. '
              || '★ 대상 — 본식 스냅처럼 예식 당일 홀에 들어오는 업체. '
              || '스튜디오는 박람회에서 계약한 홀 제휴 업체이고 촬영도 홀 밖에서 하므로 '
              || '승인 대상이 아닐 가능성이 크다. 다만 임의로 판단하지 말고 함께 확인할 것.'
