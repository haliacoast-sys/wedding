-- 외부 스튜디오의 정체 확인 (2026-08-09)
--
-- "외부"라고 불러 왔지만 실제로는 박람회에서 계약한 웨딩홀 제휴 업체다.
-- 홀과 무관한 제3의 업체가 아니라는 점이 세 가지를 바꾼다.
--
--   ① 약관 제6조 사전 승인 — 홀이 이미 제휴 관계로 인정한 업체라면 별도 승인 대상이
--      아닐 가능성이 크다. 다만 임의로 단정하지 말고 확인은 해야 한다.
--   ② 패키지 조정 협상 — 오히려 근거가 세진다. 홀 입장에서 "우리 제휴사에서 스튜디오를
--      하니 패키지의 스튜디오 몫을 빼달라"는 요구는 남의 업체를 쓸 때보다 받아들이기 쉽다.
--   ③ 14일 숙려기간 — 박람회 현장 계약이므로 홀 계약과 같은 숙려 규정이 적용될 수 있다.
--      홀 계약 기준 만료일은 2026-08-23 이다. 스튜디오 계약일이 같은 날이면 마감도 같다.
--      이 기간이 지나면 계약금을 돌려받을 수 없다.

update public.budget_items
   set label = '스튜디오 웨딩 화보 (홀 제휴 업체)',
       memo  = '2026-08-09 확인 — 박람회에서 계약한 웨딩홀 제휴 업체다. 홀과 무관한 외부 업체가 아니다. '
               || '원하는 스타일이어서 홀 패키지의 스튜디오 대신 이쪽으로 진행한다. '
               || '★ 계약 금액 미확인 — 확인되면 채울 것. '
               || '★ 14일 숙려기간 — 박람회 현장 계약이면 홀 계약과 같은 숙려 규정이 적용될 수 있다. '
               || '홀 계약 기준 만료일은 2026-08-23 이다. 계약일과 환불 조건을 지금 확인할 것. '
               || '지나면 계약금을 돌려받지 못한다. '
               || '★ 확인할 것 — 촬영일 헤어·메이크업 포함 여부, 헬퍼 포함 여부, 원본 제공 조건.'
 where label = '스튜디오 웨딩 화보 (외부 계약)';

