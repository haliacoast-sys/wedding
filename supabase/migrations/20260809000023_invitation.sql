-- 청첩장 확정 (2026-08-09)
--
-- 종이 청첩장 100,000원으로 계약하고, 모바일 청첩장은 서비스로 받는다.
-- wedding.html 별도 비용 표에 "청첩장 / 모바일 100,000 / 50,000 · 모바일은 청첩장 계약 시 서비스"
-- 라고 명시돼 있다. 계약하기로 했으므로 모바일은 0원이다.

update public.budget_items
   set label    = '모바일 청첩장 (종이 계약 시 서비스)',
       estimate = 0,
       memo     = '2026-08-09 확정 — 종이 청첩장을 계약하므로 서비스로 받는다. 별도 비용 표 기준 50,000원 상당. '
                  || '★ 확인할 것 — 하객에게 보낼 링크 형식과 수정 가능 횟수, 지도·계좌 안내 포함 여부. '
                  || '모바일 청첩장은 발송 후에도 내용을 고쳐야 하는 일이 자주 생긴다(시간·주차 안내 등).'
 where label = '모바일 청첩장';

update public.budget_items
   set label = '종이 청첩장',
       memo  = '2026-08-09 계약 예정 — 별도 비용 표 기준 100,000원. 이 계약으로 모바일 청첩장이 서비스로 딸려온다. '
              || '★ 부수는 하객 수의 60% 정도면 충분하다. 부부·가족 단위로 한 장씩 나가기 때문이다. '
              || '따라서 양가 하객 수 러프 집계(2026-08-23)가 선행돼야 부수를 정할 수 있다. '
              || '★ 100,000원이 몇 부 기준인지 확인할 것. 부수 초과분 단가도 함께 물어볼 것.'
 where label = '종이 청첩장';

-- 계약과 발주는 다른 일이다. 계약은 지금, 인쇄 발주는 문구가 확정된 뒤다.
update public.tasks
   set note = coalesce(note || ' ', '')
              || '★ 청첩장 업체 계약은 미리 해도 되지만 인쇄 발주는 이 시점이다 — 하객 명단이 확정돼야 '
              || '부수가 나오고, 문구에 예식 정보가 정확히 들어가야 한다. 인쇄에 7~10일 걸린다.'
 where title = '청첩장 제작 발주'
   and note not like '%청첩장 업체 계약은 미리 해도 되지만%';

update public.tasks
   set note = coalesce(note || ' ', '')
              || '★ 모바일 청첩장은 종이 청첩장 계약에 서비스로 포함된다(별도 비용 표 기준 50,000원 상당). '
              || '따로 만들거나 결제하지 말 것. '
              || '★ 발송 후에도 고칠 일이 생긴다(주차 안내, 셔틀 정보 등). 수정 가능 횟수를 미리 확인할 것.'
 where title = '모바일 청첩장 제작 및 검수'
   and note not like '%종이 청첩장 계약에 서비스로 포함%';
