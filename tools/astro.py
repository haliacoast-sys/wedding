def _ser(terms, tau):
    return sum(A*math.cos(B+C*tau) for A,B,C in terms)

def earth_L_R(jde):
    tau=(jde-2451545.0)/365250.0
    L=(_ser(L0,tau)+_ser(L1,tau)*tau+_ser(L2,tau)*tau**2+_ser(L3,tau)*tau**3+_ser(L4,tau)*tau**4+_ser(L5,tau)*tau**5)/1e8
    R=(_ser(R0,tau)+_ser(R1,tau)*tau+_ser(R2,tau)*tau**2+_ser(R3,tau)*tau**3+_ser(R4,tau)*tau**4)/1e8
    return math.degrees(L)%360.0, R

def nutation_dpsi(jde):
    T=(jde-2451545.0)/36525.0
    om=125.04452-1934.136261*T+0.0020708*T*T+T**3/450000.0
    Ls=280.4665+36000.7698*T
    Lm=218.3165+481267.8813*T
    dpsi=(-17.20*math.sin(om*D2R)-1.32*math.sin(2*Ls*D2R)
          -0.23*math.sin(2*Lm*D2R)+0.21*math.sin(2*om*D2R))  # arcsec
    return dpsi/3600.0

def sun_apparent_longitude(jde):
    T=(jde-2451545.0)/36525.0
    L,R=earth_L_R(jde)
    theta=(L+180.0)%360.0
    theta=theta-0.09033/3600.0           # FK5
    theta=theta+nutation_dpsi(jde)        # nutation
    theta=theta-(20.4898/R)/3600.0        # aberration
    return theta%360.0

def delta_T(year):
    # Espenak/Meeus polynomial (2005-2050 & neighbours)
    if 1986<=year<2005:
        t=year-2000.0
        return (63.86+0.3345*t-0.060374*t**2+0.0017275*t**3+0.000651814*t**4+0.00002373599*t**5)
    if 2005<=year<2050:
        t=year-2000.0
        return 62.92+0.32217*t+0.005589*t*t
    if 2050<=year<=2150:
        return -20+32*((year-1820)/100.0)**2-0.5628*(2150-year)
    t=year-2000.0
    return 62.92+0.32217*t+0.005589*t*t

def jd_to_dt_utc(jd):
    jd=jd+0.5
    Z=int(jd); F=jd-Z
    if Z<2299161: A=Z
    else:
        alpha=int((Z-1867216.25)/36524.25); A=Z+1+alpha-int(alpha/4)
    B=A+1524; C=int((B-122.1)/365.25); D=int(365.25*C); E=int((B-D)/30.6001)
    day=B-D-int(30.6001*E)+F
    month=E-1 if E<14 else E-13
    year=C-4716 if month>2 else C-4715
    di=int(day); frac=day-di
    secs=frac*86400.0
    return datetime(year,month,di,tzinfo=timezone.utc)+timedelta(seconds=secs)

def dt_to_jd(dt):
    dt=dt.astimezone(timezone.utc)
    y,m=dt.year,dt.month
    d=dt.day+(dt.hour+dt.minute/60.0+dt.second/3600.0)/24.0
    if m<=2: y-=1; m+=12
    A=int(y/100); B=2-A+int(A/4)
    return int(365.25*(y+4716))+int(30.6001*(m+1))+d+B-1524.5

def solar_term_kst(year, target_deg):
    """target_deg 태양황경에 도달하는 시각 (KST)"""
    # 초기 추정: 황경 0 = 춘분(~3/20)
    approx = 2451545.0 + 365.2422*(year-2000) + (target_deg/360.0)*365.2422 - 79.0
    jde = approx
    for _ in range(60):
        lam = sun_apparent_longitude(jde)
        diff = (lam - target_deg + 180) % 360 - 180
        jde -= diff*365.2422/360.0
        if abs(diff) < 1e-9: break
    ut = jde - delta_T(year)/86400.0
    return jd_to_dt_utc(ut).astimezone(KST)

